#!/usr/bin/env python3
"""Extract browser cookies and output in Netscape format for yt-dlp.

Usage: python3 extract_cookies.py <browser> <domain> <output_file>
Supported browsers: chrome, firefox, edge, brave, opera, chromium
"""

import sys

def extract(browser, domain, output_file):
    try:
        import browser_cookie3

        cj = getattr(browser_cookie3, browser)(domain_name=domain)
        cookies = list(cj)
        if not cookies:
            print(f"NO_COOKIES: no cookies found for {domain} in {browser}", file=sys.stderr)
            return 1

        with open(output_file, 'w') as f:
            f.write("# Netscape HTTP Cookie File\n")
            f.write("# Generated by browser_cookie3\n\n")
            for c in cookies:
                domain_str = c.domain if c.domain.startswith('.') else f'.{c.domain}'
                flag = 'TRUE' if domain_str.startswith('.') else 'FALSE'
                path = c.path or '/'
                secure = 'TRUE' if c.secure else 'FALSE'
                exp = str(int(c.expires)) if c.expires else '0'
                f.write(f"{domain_str}\t{flag}\t{path}\t{secure}\t{exp}\t{c.name}\t{c.value}\n")

        print(f"EXTRACTED: {len(cookies)} cookies from {browser} for {domain}", file=sys.stderr)
        return 0
    except ImportError:
        print("NO_MODULE: browser_cookie3 not installed", file=sys.stderr)
        return 2
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 3


if __name__ == '__main__':
    if len(sys.argv) != 4:
        print(f"Usage: {sys.argv[0]} <browser> <domain> <output_file>", file=sys.stderr)
        sys.exit(1)
    sys.exit(extract(sys.argv[1], sys.argv[2], sys.argv[3]))
